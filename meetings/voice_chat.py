"""Живой разговор «Фокуса»: приветствие, вежливость, «что ты умеешь», время, шутки.

Только заранее написанные фразы: модель здесь не вызывается, данные компании не читаются,
поэтому такие ответы можно озвучивать при любой аудитории. Всё, что похоже на рабочий
вопрос, уходит дальше — в документы, обзор или брифинг — с теми же проверками прав.
"""
import random
import re
from datetime import datetime
from zoneinfo import ZoneInfo

ZONE = ZoneInfo('Europe/Minsk')
WEEKDAYS = ('понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота', 'воскресенье')
MONTHS = ('января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября',
          'октября', 'ноября', 'декабря')

GREETING = re.compile(
    r'^(?:привет(?:ик|ствую)?|здравствуй(?:те)?|здрасьте|добр(?:ое|ый|ой)\s+(?:утро|день|вечер|ночи)|доброго\s+\w+|'
    r'хай|хелло|салют|здорово)'
    r'(?:[\s,!.]+фокус(?:е|а)?)?(?![а-яё])[\s,!.?]*', re.I)
# Обращение без приветствия: «Окей, Фокус, …», «Слушай, Фокус», «Фокус, …» — просто убираем.
# «Фокус» само по себе — обычное слово («Фокус на сроках…»), поэтому без «окей/эй» нужна запятая.
CALL = re.compile(r'^(?:(?:окей|окэй|ок|ok|okay|эй|слушай|алло)[\s,!.]+фокус(?:е|а)?(?![а-яё])[\s,!.?]*'
                  r'|фокус(?:е|а)?\s*[,!]+\s*)', re.I)
NAME_ONLY = re.compile(r'^фокус(?:е|а)?[\s,!.?]*$', re.I)

# (тема, шаблон). Срабатывает, только если вся реплика — это разговорная фраза.
TOPICS = (
    ('how', r'как\s+(?:у\s+тебя\s+|твои\s+|ты\s+|сам\s+|поживаешь|жизнь|настроение|оно)?(?:дела|жизнь|настроение|поживаешь|сам|ты|оно)?'
            r'|что\s+нового|как\s+поживаешь|как\s+ты'),
    ('thanks', r'спасибо(?:\s+большое|\s+огромное)?|благодарю|спс|пасиб\w*|мерси|thanks'),
    ('who', r'кто\s+ты(?:\s+такой)?|ты\s+кто(?:\s+такой)?|как\s+тебя\s+зовут|что\s+ты\s+такое|представься'),
    ('help', r'что\s+(?:ты\s+)?(?:умеешь|можешь)(?:\s+делать)?|чем\s+(?:ты\s+)?(?:можешь\s+)?помочь|помоги|помощь|справка|'
             r'что\s+(?:у\s+тебя\s+)?можно\s+спросить|что\s+спросить|как\s+(?:тобой|с\s+тобой)\s+\w+'),
    ('bye', r'пока(?:\s+пока)?|до\s+свидания|до\s+встречи|до\s+завтра|спокойной\s+ночи|всего\s+доброго|увидимся|бывай'),
    ('time', r'(?:который|сколько)\s+(?:сейчас\s+)?час(?:ов)?|сколько\s+(?:сейчас\s+)?времени|время'),
    ('date', r'какое\s+(?:сегодня\s+)?число|какой\s+сегодня\s+день|какая\s+(?:сегодня\s+)?дата|какой\s+день\s+недели|'
             r'что\s+(?:у\s+нас\s+)?сегодня\s+за\s+день'),
    ('joke', r'(?:расскажи\s+)?(?:шутк\w*|анекдот\w*)|пошути|рассмеши|повесели'),
    ('praise', r'молодец|умница|умничка|класс|круто|супер|отлично|хорошо|здорово|ты\s+лучш\w+|люблю\s+тебя'),
    ('rude', r'(?:ты\s+)?(?:тупой|тупица|глупый|дурак|бесполезн\w*|идиот)'),
    ('ok', r'ок(?:ей)?|понятно|ясно|ладно|угу|ага|да|нет|хм+'),
)
TOPIC_RE = [(name, re.compile(rf'^(?:{pattern})[\s,!.?)]*(?:фокус(?:е|а)?)?[\s,!.?]*$', re.I)) for name, pattern in TOPICS]

JOKES = (
    'Почему фотокнига не опаздывает? Потому что у неё переплёт, а не отговорки.',
    'Встреча, которая могла быть письмом, всё-таки стала встречей. Зато я написал протокол.',
    'Дедлайн — это когда задача уже в календаре, а мотивация ещё в пути.',
    'Я бы рассказал шутку про брак в печати, но её пришлось бы перепечатывать.',
    'Говорят, лучший KPI — это выспавшийся руководитель. Жаль, его нет в витрине.',
)


def first_name(user):
    name = ' '.join(str((user or {}).get('name') or '').split())
    return name.split(' ')[0] if name else ''


def part_of_day(now):
    hour = now.astimezone(ZONE).hour
    if 5 <= hour < 12:
        return 'Доброе утро'
    if 12 <= hour < 18:
        return 'Добрый день'
    if 18 <= hour < 23:
        return 'Добрый вечер'
    return 'Доброй ночи'


def greeting(user, now):
    name = first_name(user)
    return f'{part_of_day(now)}, {name}!' if name else f'{part_of_day(now)}!'


def _date_text(now):
    local = now.astimezone(ZONE)
    return f'{WEEKDAYS[local.weekday()]}, {local.day} {MONTHS[local.month - 1]}'


HELP = ('Я подскажу, что важного сегодня, сколько открытых и просроченных задач, как идут показатели, '
        'и найду ответ в документах — со ссылкой на источник. Например, спросите: «Что важного сегодня?»')


def _reply(topic, user, now, pick):
    name = first_name(user)
    to = f', {name}' if name else ''
    if topic == 'how':
        return pick(['Всё отлично, спасибо! Документы на месте, задачи посчитаны. Чем помочь?',
                     f'Хорошо{to}! Готов искать ответы. Что интересует?',
                     'Работаю с удовольствием. Спросите про задачи, показатели или документы.'])
    if topic == 'thanks':
        return pick(['Пожалуйста! Обращайтесь.', f'Всегда рад помочь{to}.', 'Не за что. Если что — я рядом.'])
    if topic == 'who':
        return ('Я Фокус — помощник по встречам и знаниям команды. Отвечаю только по данным, к которым у вас есть доступ, '
                'и всегда показываю источник.')
    if topic == 'help':
        return HELP
    if topic == 'bye':
        return pick([f'До встречи{to}! Хорошего дня.', 'Пока! Зовите, если понадоблюсь.', 'Всего доброго!'])
    if topic == 'time':
        return f'Сейчас {now.astimezone(ZONE):%H:%M}.'
    if topic == 'date':
        return f'Сегодня {_date_text(now)}.'
    if topic == 'joke':
        return pick(JOKES)
    if topic == 'praise':
        return pick(['Спасибо, приятно!', f'Спасибо{to}! Стараюсь.', 'Рад, что пригодился.'])
    if topic == 'rude':
        return pick(['Бывает, я ещё учусь. Попробуйте спросить по-другому — например, «Что важного сегодня?»',
                     'Понимаю, неприятно, когда не помогаю. Скажите, что нужно, — попробую ещё раз.'])
    if topic == 'ok':
        return pick(['Хорошо. Если появится вопрос — я здесь.', 'Понял. Чем ещё помочь?'])
    return None


def split_greeting(text):
    """(есть приветствие, остаток реплики без приветствия и обращения по имени)."""
    text = (text or '').strip()
    called = CALL.match(text)
    if called and called.end():
        text = text[called.end():].strip()
    found = GREETING.match(text)
    if not found:
        return False, text
    return True, text[found.end():].strip()


def small_talk(text, user, now=None, pick=random.choice):
    """Ответ на разговорную реплику или None, если это рабочий вопрос."""
    now = now or datetime.now(ZONE)
    clean = ' '.join(str(text or '').replace('ё', 'е').replace('Ё', 'Е').split()).strip(' ,.!?')
    if not clean or NAME_ONLY.match(clean):
        return f'{greeting(user, now)} Слушаю.'
    greeted, rest = split_greeting(clean)
    if not greeted and not rest:  # «Окей, Фокус» без вопроса
        return f'{greeting(user, now)} Слушаю.'
    if greeted and not rest:
        return pick([f'{greeting(user, now)} Чем помочь?', f'{greeting(user, now)} Рад слышать. Что подсказать?',
                     f'Привет, {first_name(user)}! Я на связи.' if first_name(user) else 'Привет! Я на связи.'])
    body = rest
    for topic, pattern in TOPIC_RE:
        if pattern.match(body):
            reply = _reply(topic, user, now, pick)
            return f'{greeting(user, now)} {reply}' if greeted and topic != 'bye' else reply
    return None


def suggestion():
    return 'Можно спросить: «Что важного сегодня?» или «Сколько просроченных задач?»'
